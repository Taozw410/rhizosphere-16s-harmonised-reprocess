suppressPackageStartupMessages(library(parallel))
t0 <- Sys.time()
cl <- makeCluster(3, outfile = "")
pids <- unlist(parLapply(cl, 1:3, function(i) Sys.getpid()))
libok <- unlist(parLapply(cl, 1:3, function(i) { suppressPackageStartupMessages(require(dada2)); as.character(packageVersion("dada2")) }))
stopCluster(cl)
cat("worker pids :", paste(pids, collapse = ", "), "\n")
cat("distinct    :", length(unique(pids)), "\n")
cat("dada2 on wkr:", paste(unique(libok), collapse = ","), "\n")
cat("cluster boot time (s):", round(as.numeric(difftime(Sys.time(), t0, units="secs")),1), "\n")
